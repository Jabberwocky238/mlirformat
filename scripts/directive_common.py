#!/usr/bin/env python3
"""Generates `OmpCommon.td` / `AccCommon.td`: what `mlir-tblgen --gen-directive-decl` makes of
llvm's `OMP.td` / `ACC.td` at build time (`mlir/tools/mlir-tblgen/DirectiveCommonGen.cpp`), so
the OpenMP / OpenACC ODS can be read without an LLVM build.

    python3 scripts/directive_common.py --llvm $LLVM --mlirformat target/release/mlirformat

The records come from `mlirformat tblgen --dump-json`; the files land in `td/` at the path a
23.1.5 build puts them.
"""

import argparse
import json
import subprocess
from pathlib import Path

# (directives file under llvm/include, the dialect's TableGen name, the output under td/)
DIRECTIVES = [
    ("llvm/Frontend/OpenMP/OMP.td", "OpenMP", "mlir/Dialect/OpenMP/OmpCommon.td"),
    ("llvm/Frontend/OpenACC/ACC.td", "OpenACC", "mlir/Dialect/OpenACC/AccCommon.td"),
]

HEADER = """/*===- TableGen'erated file -------------------------------------*- C++ -*-===*\\
|*                                                                            *|
|* Generated by scripts/directive_common.py (gen-directive-decl) from %s
|*                                                                            *|
\\*===----------------------------------------------------------------------===*/

"""


def dump(mlirformat: str, include: Path, td: str):
    path = include / td
    out = subprocess.run([mlirformat, "tblgen", "--dump-json", str(path), "-I", str(include), "-I", str(path.parent)], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit(f"{td}: {out.stderr.strip()}")
    return json.loads(out.stdout)


def spelling(d, rec) -> str:
    """`getSpellingForIdentifier`: the first of the oldest spellings."""
    best, oldest = "not found", None
    for s in rec.get("spellings", []):
        sp = d[s["def"]]
        if oldest is None or sp["minVersion"] < oldest:
            best, oldest = sp["spelling"], sp["minVersion"]
    return best


def emit(d, dialect: str) -> str:
    """`emitDecls`."""
    namespace = d[d["!instanceof"]["DirectiveLanguage"][0]]["cppNamespace"]
    out = []
    for name in sorted(d["!instanceof"]["Clause"]):
        c = d[name]
        values = c.get("allowedClauseValues") or []
        if not values:
            continue
        enum = c["enumClauseValue"]
        defs = []
        for i, v in enumerate(values):
            val = d[v["def"]]
            if not val["isUserValue"]:
                continue
            # `getFormattedName`: the name, else the spelling, spaces as underscores.
            text = (val.get("name") or spelling(d, val)).replace(" ", "_")
            case = text.lower()
            case = case[0].upper() + case[1:]
            cv = enum + text
            out.append(f'def {cv} : I32EnumAttrCase<"{case}", {i}, "{text}">;\n')
            defs.append(cv)
        out.append(f"def {enum}: I32EnumAttr<\n")
        out.append(f'  "Clause{enum}",\n')
        out.append(f'  "{enum} Clause",\n')
        out.append("  [" + ", ".join(defs) + "]> {\n")
        out.append(f'    let cppNamespace = "::mlir::{namespace}";\n')
        out.append("    let genSpecializedAttr = 0;\n")
        out.append("}\n")
        out.append(f'def {enum}Attr : EnumAttr<{dialect}_Dialect, {enum}, "{enum.lower()}">;\n')
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--llvm", required=True)
    ap.add_argument("--mlirformat", required=True)
    ap.add_argument("-o", default=str(Path(__file__).resolve().parent.parent / "td"))
    opts = ap.parse_args()
    include = Path(opts.llvm) / "llvm" / "include"
    for td, dialect, out in DIRECTIVES:
        d = dump(opts.mlirformat, include, td)
        path = Path(opts.o) / out
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER % td + emit(d, dialect))
        print(f"{path}")


if __name__ == "__main__":
    main()
