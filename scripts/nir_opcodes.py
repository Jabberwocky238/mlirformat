"""Writes src/dialects/nir.gen.rs: the nir dialect, one op for each ALU opcode of Mesa's NIR, from Mesa's
src/compiler/nir/nir_opcodes.py.

    python3 scripts/nir_opcodes.py MESA/src/compiler/nir/nir_opcodes.py MESA_VERSION

Each opcode `x` is `nir.x`: its sources `src0` .. and its result, every type written
(`nir.fadd %a, %b : (f32, f32) -> f32`), and `exact` (NIR's exact flag: no value-changing optimization). The table
`NirDialect::OPCODES` keeps what nir_opcodes.py says of each: sources, their sizes and types, the result's size and
type, the algebraic properties.
"""
import importlib.util
import sys
from pathlib import Path


class Opcodes:
    """nir_opcodes.py's opcodes, as the Rust the dialect is"""

    BASES = {"float": "Float", "int": "Int", "uint": "Uint", "bool": "Bool"}

    def __init__(self, path, version):
        spec = importlib.util.spec_from_file_location("nir_opcodes", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.opcodes = [module.opcodes[n] for n in sorted(module.opcodes)]
        self.version = version

    @staticmethod
    def rust_name(name):
        return "".join(p[:1].upper() + p[1:] for p in name.split("_")) + "Op"

    @staticmethod
    def ty(t):
        base = t.rstrip("0123456789")
        bits = t[len(base):] or "0"
        return f"NirType {{ base: NirBase::{Opcodes.BASES[base]}, bits: {bits} }}"

    def op(self, o):
        srcs = [f"src{i}" for i in range(o.num_inputs)]
        operands = " `,` ".join(f"${s}" for s in srcs)
        types = " ".join(f"${s}" for s in srcs)
        head = f"{operands} attr-dict" if srcs else "attr-dict"
        fmt = f"{head} `:` functional-type({types}, $result)"
        out = [f'#[mlir::op("nir.{o.name}", format = "{fmt}", results(result))]', f"pub struct {Opcodes.rust_name(o.name)}<'a> {{"]
        for s in srcs:
            out += [f"    #[slot({s}_ty)]", f"    pub {s}: Value<'a>,"]
        out += [f"    pub {s}_ty: Type<'a>," for s in srcs]
        out += ["    pub exact: bool,", "    pub result: Type<'a>,", "}", ""]
        return out

    def entry(self, o):
        props = o.algebraic_properties.split()
        flags = ", ".join(f"{p}: {('true' if k in props else 'false')}" for p, k in [("commutative", "commutative"), ("associative", "associative"), ("two_src_commutative", "2src_commutative"), ("selection", "selection")])
        inputs = ", ".join(f"({size}, {Opcodes.ty(t)})" for size, t in zip(o.input_sizes, o.input_types))
        return f'        NirOpcode {{ name: "nir.{o.name}", inputs: &[{inputs}], output: ({o.output_size}, {Opcodes.ty(o.output_type)}), {flags} }},'

    def rust(self):
        out = [
            f"// Generated by scripts/nir_opcodes.py from Mesa {self.version}'s src/compiler/nir/nir_opcodes.py: do not edit.",
            "",
            "use crate::{Effects, OpInfo, Trait, Type, Value, mlir};",
            "",
            "/// A NIR type's base: what its bits mean",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub enum NirBase {",
            "    Float,",
            "    Int,",
            "    Uint,",
            "    Bool,",
            "}",
            "",
            "/// A source's or result's NIR type: a base and a bit size (0: any size, the same as the others of size 0)",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct NirType {",
            "    pub base: NirBase,",
            "    pub bits: u8,",
            "}",
            "",
            "/// What nir_opcodes.py says of an opcode. A size is a vector's components; 0 is per component (the",
            "/// result's size, a source's too).",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct NirOpcode<'n> {",
            "    pub name: &'n str,",
            "    pub inputs: &'n [(u8, NirType)],",
            "    pub output: (u8, NirType),",
            "    pub commutative: bool,",
            "    pub associative: bool,",
            "    /// the first two sources commute (ffma, fdot …)",
            "    pub two_src_commutative: bool,",
            "    pub selection: bool,",
            "}",
            "",
        ]
        for o in self.opcodes:
            out += self.op(o)
        out += [
            "/// The nir dialect. Its ops compute and nothing else: no effects, always speculatable; a commutative",
            "/// opcode's op commutes.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]",
            "pub struct NirDialect;",
            "",
            "impl crate::Dialect for NirDialect {",
            "    fn namespace(&self) -> &'static str {",
            '        "nir"',
            "    }",
            "",
            "    fn ops(&self) -> crate::__Vec<crate::Template> {",
            "        crate::__vec![",
        ]
        out += [f"            <{Opcodes.rust_name(o.name)} as crate::Op>::template()," for o in self.opcodes]
        out += ["        ]", "    }", "", "    fn op_infos(&self) -> crate::__Vec<crate::OpInfo> {", "        crate::__vec!["]
        for o in self.opcodes:
            traits = ["Trait::AlwaysSpeculatableImplTrait", "Trait::ConditionallySpeculatable", "Trait::MemoryEffectOpInterface"]
            props = o.algebraic_properties.split()
            if "commutative" in props or ("2src_commutative" in props and o.num_inputs == 2):
                traits.append("Trait::IsCommutative")
            out.append(f'            OpInfo {{ name: "nir.{o.name}", traits: &[{", ".join(traits)}], effects: Effects::Known(&[]), inherent: &["exact"] }},')
        out += ["        ]", "    }", "}", ""]
        out += ["impl NirDialect {", "    /// Every opcode, sorted by name", "    pub const OPCODES: &[NirOpcode<'_>] = &["]
        out += [self.entry(o) for o in self.opcodes]
        out += ["    ];", "", "    pub fn opcode(name: &str) -> Option<&NirOpcode<'_>> {", "        NirDialect::OPCODES.binary_search_by(|o| o.name.cmp(name)).ok().map(|i| &NirDialect::OPCODES[i])", "    }", "}", ""]
        return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ops = Opcodes(sys.argv[1], sys.argv[2])
    Path(__file__).resolve().parent.parent.joinpath("src/dialects/nir.gen.rs").write_text(ops.rust())
