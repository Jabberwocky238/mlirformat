#!/usr/bin/env python3
"""Writes src/verifier/spirv.gen.rs: every SPIR-V enum attribute of td/.../SPIRVBase.td with its
cases (`SPIRV_I32EnumAttr` / `SPIRV_BitEnumAttr`), for the verifier's `symbolizeEnum`.
    scripts/spirv_enums.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")
TD = os.path.join(ROOT, "td/mlir/Dialect/SPIRV/IR/SPIRVBase.td")
OUT = os.path.join(ROOT, "src/verifier/spirv.gen.rs")

src = open(TD).read()
# def SPIRV_S_Device : I32EnumAttrCase<"Device", 1>;  /  I32BitEnumAttrCaseBit<"Aligned", 1>  /  ..None<"None">
cases = {}
for m in re.finditer(r'^def (\w+)\s*:\s*I32(EnumAttrCase|BitEnumAttrCaseBit|BitEnumAttrCaseNone)<"(\w+)"(?:,\s*(\d+))?', src, re.M):
    name, kind, sym, n = m.groups()
    value = 0 if kind == "BitEnumAttrCaseNone" else (1 << int(n) if kind == "BitEnumAttrCaseBit" else int(n))
    cases[name] = (sym, value)
# A group case (`I32BitEnumAttrCaseGroup<"X", [A, B]>`) is the union of its members.
for m in re.finditer(r'^def (\w+)\s*:\s*I32BitEnumAttrCaseGroup<"(\w+)",\s*\[([^\]]*)\]', src, re.M):
    name, sym, members = m.groups()
    value = 0
    for c in re.findall(r"\w+", members):
        value |= cases[c][1]
    cases[name] = (sym, value)

enums = []
for m in re.finditer(r'^def SPIRV_(\w+)Attr\s*:\s*SPIRV_(I32EnumAttr|BitEnumAttr)<\s*"(\w+)",\s*"[^"]*",\s*"(\w+)",\s*\[([^\]]*)\]', src, re.M | re.S):
    _, kind, cpp, mnemonic, members = m.groups()
    listed = [cases[c] for c in re.findall(r"\w+", members)]
    enums.append((mnemonic, cpp, kind == "BitEnumAttr", listed))
enums.sort()

with open(OUT, "w") as f:
    f.write("//! Generated by `scripts/spirv_enums.py` from `SPIRVBase.td`. Do not edit.\n\n")
    f.write("use super::SpirvEnum;\n\n")
    f.write("/// Every SPIR-V enum attribute, by mnemonic.\n")
    f.write("pub(super) const ENUMS: &[SpirvEnum] = &[\n")
    for mnemonic, cpp, bits, listed in enums:
        body = ", ".join(f'("{s}", {v:#x})' for s, v in listed)
        f.write(f'    SpirvEnum {{ mnemonic: "{mnemonic}", name: "{cpp}", bits: {"true" if bits else "false"}, cases: &[{body}] }},\n')
    f.write("];\n")
print(f"{OUT}: {len(enums)} enums")
